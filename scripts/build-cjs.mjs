// Generate cjs/index.cjs from the ESM sources. The ESM files are the single
// source of truth. Each module is wrapped in a factory and wired through an
// in-file registry so the generated artifact is dependency free.
// Run with --check in CI to prove the committed artifact matches the sources.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SCRIPT_DIR, '..');
const TARGET = join(ROOT, 'cjs', 'index.cjs');

// Import order matters: detector registration must happen before index.mjs
// re-exports the registry.
const MODULES = [
  'src/util.mjs',
  'src/detectors/registry.mjs',
  'src/detectors/builtins.mjs',
  'src/detectors/index.mjs',
  'src/finder.mjs',
  'src/ignore.mjs',
  'src/scanner.mjs',
  'src/baseline.mjs',
  'src/output.mjs',
  'src/index.mjs',
];

function resolveId(spec, fromId) {
  if (!spec.startsWith('.')) return spec;
  const parts = fromId.split('/');
  parts.pop();
  for (const segment of spec.split('/')) {
    if (segment === '.' || segment === '') continue;
    if (segment === '..') parts.pop();
    else parts.push(segment);
  }
  return parts.join('/');
}

function transform(source, id) {
  const exports = [];
  let body = source;

  body = body.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm,
    (_m, names, spec) => spec.startsWith('node:')
      ? `const {${names}} = require('${spec}');`
      : `const {${names}} = __internalRequire('${resolveId(spec, id)}');`);
  body = body.replace(/^import\s+'([^']+)';?[ \t]*$/gm,
    (_m, spec) => spec.startsWith('node:')
      ? `require('${spec}');`
      : `__internalRequire('${resolveId(spec, id)}');`);
  body = body.replace(/^export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)/gm,
    (_m, name) => { exports.push({ exported: name, local: name }); return `function ${name}`; });
  body = body.replace(/^export\s+class\s+([A-Za-z0-9_$]+)/gm,
    (_m, name) => { exports.push({ exported: name, local: name }); return `class ${name}`; });
  body = body.replace(/^export\s+(const|let|var)\s+([A-Za-z0-9_$]+)/gm,
    (_m, keyword, name) => { exports.push({ exported: name, local: name }); return `${keyword} ${name}`; });
  body = body.replace(/^export\s*\{([^}]*)\}\s*(?:from\s*'([^']+)')?;?[ \t]*$/gm, (_m, names, spec) => {
    if (spec) {
      const sourceId = resolveId(spec, id);
      return names.split(',').map((part) => {
        const trimmed = part.trim();
        if (!trimmed) return '';
        const alias = trimmed.split(/\s+as\s+/);
        const local = alias[0].trim();
        const exported = alias.length === 2 ? alias[1].trim() : local;
        return `__exports.${exported} = __internalRequire('${sourceId}').${local};`;
      }).filter(Boolean).join('\n');
    }
    for (const part of names.split(',')) {
      const trimmed = part.trim();
      if (!trimmed) continue;
      const alias = trimmed.split(/\s+as\s+/);
      exports.push({ exported: alias.length === 2 ? alias[1].trim() : alias[0].trim(), local: alias[0].trim() });
    }
    return '';
  });

  if (/^export\s/m.test(body)) throw new Error(`build-cjs: unhandled export form in ${id}`);

  const tail = exports.length
    ? exports.map((entry) => `__exports.${entry.exported} = ${entry.local};`).join('\n')
    : '';
  return { body: body.trimEnd(), tail };
}

function build() {
  const parts = [];
  parts.push("'use strict';");
  parts.push('// Generated by scripts/build-cjs.mjs from src/*.mjs. Do not edit directly.');
  parts.push('// Source of truth: src/*.mjs. Run "npm run build:cjs" after editing the ESM sources.');
  parts.push('const __internalModules = new Map();');
  parts.push('function __internalDefine(id, factory) { __internalModules.set(id, { factory, exports: {}, loaded: false }); }');
  parts.push('function __internalRequire(spec) {');
  parts.push('  const entry = __internalModules.get(spec);');
  parts.push("  if (!entry) throw new Error('secretsweep: unknown internal module ' + spec);");
  parts.push('  if (!entry.loaded) { entry.loaded = true; entry.factory(entry.exports, __internalRequire); }');
  parts.push('  return entry.exports;');
  parts.push('}');
  for (const id of MODULES) {
    const source = readFileSync(join(ROOT, id), 'utf8');
    const { body, tail } = transform(source, id);
    parts.push(`__internalDefine('${id}', function (__exports, __internalRequire) {`);
    parts.push(`// ---- ${id} ----`);
    parts.push(body);
    if (tail) parts.push(tail);
    parts.push('});');
  }
  parts.push("module.exports = __internalRequire('src/index.mjs');");
  parts.push('');
  return parts.join('\n');
}

const output = build();
if (process.argv.includes('--check')) {
  if (!existsSync(TARGET) || readFileSync(TARGET, 'utf8') !== output) {
    process.stderr.write('cjs/index.cjs is missing or out of date; run npm run build:cjs\n');
    process.exit(1);
  }
  process.stdout.write('cjs/index.cjs is up to date\n');
} else {
  writeFileSync(TARGET, output);
  process.stdout.write(`wrote ${TARGET} (${output.length} bytes)\n`);
}
